// Helper to construct initial price history with small variance
function generateInitialHistory(basePrice: number, points = 24): number[] {
  const history: number[] = [];
  let price = basePrice;
  for (let i = 0; i < points; i++) {
    const change = (Math.random() - 0.495) * (basePrice * 0.002);
    price += change;
    history.push(Number(price.toFixed(4)));
  }
  return history;
}

